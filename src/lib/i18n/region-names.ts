function translateRegionFallback(region: string): string {
  let out = region;
  for (const [from, to] of TOKEN_ZH) {
    out = typeof from === "string" ? out.split(from).join(to) : out.replace(from, to);
  }
  return out
    .replace(/\s*&\s*/g, "和")
    .replace(/\band\b/gi, "和")
    .replace(/\((\d+)\+\s*areas?\)/gi, "($1+地区)")
    .replace(/\((\d+)\s*areas?\)/gi, "($1地区)")
    .replace(/\((\d+)\s*countries\)/gi, "($1国)")
    .replace(/\s{2,}/g, " ")
    .trim();
}

export function regionDisplayName(region: string, locale: "en" | "zh"): string {
  if (locale !== "zh") return region;
  return regionNamesZh[region] ?? translateRegionFallback(region);
}

